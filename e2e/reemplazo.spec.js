import {test, expect} from '@playwright/test';
import {loginInBrowser, apiClient, boliviaDate, createFundedTrip, drawSignature} from './support/helpers';
test('el titular pide un reemplazo y el reemplazo rinde los gastos firmando @celular', async ({page}) => {
  const {tripId} = await createFundedTrip();
  await loginInBrowser(page, 'juan.empleado');
  await page.goto(`/dashboard/empleado/viaje/${tripId}`);
  await page.getByRole('button', {name: 'Solicitar que Otra Persona Rinda por Mí'}).click();
  await page.getByRole('button', {name: 'Selecciona un empleado...'}).click();
  await page.getByText('Ana Empleada').click();
  await page.getByRole('button', {name: 'Enviar Solicitud'}).click();
  await expect(page.getByText('Tienes una solicitud de reemplazo pendiente de revisión.')).toBeVisible();
  const reviewer = await apiClient('lucia.revisora');
  const pending = await reviewer.get('/substitution/pending');
  const list = Array.isArray(pending) ? pending : Object.values(pending).find((value) => Array.isArray(value));
  const request = list.find((item) => item.id_viaje === tripId);
  await reviewer.post(`/substitution/${request.id_solicitud}/approve`);
  const substitute = await apiClient('ana.empleada');
  await substitute.postForm('/expense/register', {id_viaje: tripId, monto_total: 35, fecha_gasto: boliviaDate(), tipo: 'S', descripcion: 'Taxi del reemplazo', id_categoria: 1});
  await page.context().clearCookies();
  await loginInBrowser(page, 'ana.empleada');
  await page.goto(`/dashboard/empleado/viaje/${tripId}`);
  await page.getByRole('button', {name: 'Confirmar Finalización'}).click();
  await expect(page.getByRole('button', {name: 'Firmar y enviar'})).toBeDisabled();
  await drawSignature(page);
  await page.getByRole('button', {name: 'Firmar y enviar'}).click();
  const owner = await apiClient('juan.empleado');
  await expect.poll(async () => (await owner.get(`/trip/${tripId}/firmas-planilla`)).preparado?.nombre).toBe('Ana Empleada');
  expect((await owner.get(`/trip/${tripId}`)).viaje.estado).toBe('EN_REVISION');
});
